"""Tests for decode_qr_codes().

QR images are generated with segno (an encoder independent of the decoder under test).
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest
import segno
from PIL import Image

from onekey_qr import decode_qr_codes

DATA_DIR = Path(__file__).parent / "data"


def to_image(qr: segno.QRCode, scale: int = 8, border: int = 4) -> np.ndarray:
    """Render a segno QR code as a grayscale image (dark modules = 0, light = 255)."""
    dark = np.array(list(qr.matrix_iter(scale=scale, border=border)), dtype=bool)
    return np.where(dark, 0, 255).astype(np.uint8)


def make_qr(text: str, scale: int = 8, **options) -> np.ndarray:
    """Return a grayscale image of a regular (non-Micro) QR code encoding `text`."""
    return to_image(segno.make(text, micro=False, **options), scale=scale)


def side_by_side(*images: np.ndarray) -> np.ndarray:
    """Place grayscale images horizontally on a white canvas (pads to the tallest one)."""
    height = max(img.shape[0] for img in images)
    padded = [np.pad(img, ((0, height - img.shape[0]), (0, 40)), constant_values=255) for img in images]
    return np.hstack(padded)


def to_bgra(gray: np.ndarray) -> np.ndarray:
    """Convert a grayscale image to BGRA, the format of a screen capture."""
    return np.dstack([gray, gray, gray, np.full_like(gray, 255)])


# --- Basics -----------------------------------------------------------------


def test_decodes_single_qr_code():
    assert decode_qr_codes(make_qr("OneKey QR test")) == ["OneKey QR test"]


def test_decodes_multiple_qr_codes():
    img = side_by_side(make_qr("first"), make_qr("second"))

    # Detection order is not guaranteed
    assert sorted(decode_qr_codes(img)) == ["first", "second"]


def test_removes_duplicate_qr_codes():
    img = side_by_side(make_qr("same"), make_qr("same"))

    assert decode_qr_codes(img) == ["same"]


def test_returns_empty_list_when_no_qr_code():
    assert decode_qr_codes(np.full((400, 400), 255, dtype=np.uint8)) == []


@pytest.mark.parametrize("scale", [2, 3, 4, 6, 8, 10])
def test_decodes_qr_code_on_screen_sized_image(scale):
    # A QR code of various sizes placed on a large screenshot-like canvas
    canvas = np.full((1080, 1920), 240, dtype=np.uint8)
    qr = make_qr("on screen", scale=scale)
    canvas[300 : 300 + qr.shape[0], 900 : 900 + qr.shape[1]] = qr

    assert decode_qr_codes(canvas) == ["on screen"]


# --- Input formats ----------------------------------------------------------


def test_decodes_bgra_screen_capture_format():
    # capture_all_monitors() returns BGRA, which is passed to zxing-cpp without conversion
    assert decode_qr_codes(to_bgra(make_qr("bgra"))) == ["bgra"]


def test_decodes_bgr_image():
    gray = make_qr("bgr")

    assert decode_qr_codes(np.dstack([gray, gray, gray])) == ["bgr"]


# --- Styles and variants ----------------------------------------------------


def test_decodes_chrome_dot_style_qr_code():
    # Generated by Google Chrome's "Create QR code for this page":
    # round dot modules, rounded finder patterns and a dinosaur logo in the center.
    # OpenCV's QRCodeDetector could not decode this image.
    img = Image.open(DATA_DIR / "chrome_dot_style_qr.png").convert("L")

    assert decode_qr_codes(np.array(img)) == ["https://github.com/takyoto/onekey-qr"]


def test_decodes_inverted_qr_code():
    # Light modules on a dark background, e.g. in dark-mode pages
    assert decode_qr_codes(255 - make_qr("inverted")) == ["inverted"]


def test_decodes_micro_qr_code():
    micro = to_image(segno.make_micro("12345"), border=2)

    assert decode_qr_codes(micro) == ["12345"]


# --- Character encodings ----------------------------------------------------

UTF8_TEXTS = [
    "こんにちは、OneKey QR",  # Japanese (3-byte UTF-8) mixed with ASCII
    "日本語のテスト文字列",
    "Emoji 🎉 test",  # 4-byte UTF-8
]


@pytest.mark.parametrize("text", UTF8_TEXTS)
@pytest.mark.parametrize("eci", [False, True], ids=["byte", "eci-utf8"])
def test_decodes_utf8_text(text, eci):
    # With eci=True, the QR code carries a "UTF-8" charset header (ECI)
    img = make_qr(text, mode="byte", encoding="utf-8", eci=eci)

    assert decode_qr_codes(img) == [text]


@pytest.mark.parametrize("text", ["こんにちは", "日本語のテスト"])
def test_decodes_kanji_mode(text):
    # Kanji mode stores Shift_JIS characters compactly; common in QR codes made in Japan.
    # OpenCV returned corrupted bytes and raised UnicodeDecodeError for these.
    assert decode_qr_codes(make_qr(text, mode="kanji")) == [text]


def test_decodes_shift_jis_byte_mode():
    # Shift_JIS bytes without an ECI header (another common style in Japan)
    assert decode_qr_codes(make_qr("日本語テキスト", mode="byte", encoding="shift_jis")) == ["日本語テキスト"]


def test_decodes_utf8_and_ascii_qr_codes_together():
    img = side_by_side(make_qr("日本語", encoding="utf-8", eci=True), make_qr("ascii"))

    assert sorted(decode_qr_codes(img)) == sorted(["日本語", "ascii"])
